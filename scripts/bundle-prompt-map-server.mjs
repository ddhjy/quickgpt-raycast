/**
 * Bundles the Prompt Map server into a single Node script that ships in
 * `assets/prompt-map/server.js`. The extension spawns it with Raycast's Node
 * runtime, outside the extension sandbox, so it cannot rely on node_modules.
 *
 * Runs automatically before `npm run dev` and `npm run build`; the output is
 * committed so Store builds work without this step.
 */

import { build } from "esbuild";
import { fileURLToPath } from "url";
import * as path from "path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

await build({
  entryPoints: [path.join(root, "src/prompt-map/server.ts")],
  outfile: path.join(root, "assets/prompt-map/server.js"),
  bundle: true,
  platform: "node",
  target: "node20",
  format: "cjs",
  minify: true,
  legalComments: "none",
  logLevel: "info",
  banner: {
    js: "/* Prompt Map server. Generated by scripts/bundle-prompt-map-server.mjs from src/prompt-map/server.ts; do not edit. */",
  },
});
